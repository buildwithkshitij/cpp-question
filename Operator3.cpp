#include<iostream>
using namespace std;

int main(){
    int x = 10;
    int y = 15;

    cout << (x > y) << endl; // False
    cout << (x < y) << endl; // True
    cout << (x >= y) << endl; // False
    cout << (x <= y) << endl; // True
    cout << (x == y) << endl; // False
    cout << (x != y) << endl; // True

    return 0;
}